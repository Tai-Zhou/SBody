	template <typename Type>
	Type Power2(Type x) {
		return x * x;
	}

	template <typename Type>
	Type Power3(Type x) {
		return x * x * x;
	}

	template <typename Type>
	Type Power4(Type x) {
		x *= x;
		return x * x;
	}

	/**
	 * @brief Square root of `x`. Return `0` if `x` is negative.
	 *
	 * @param x number
	 * @return result
	 */
	template <typename Type>
	Type SquareRoot(Type x) {
		if (x <= 0.)
			return 0.;
		return std::sqrt(x);
	}

	/**
	 * @brief Square of `x` with the sign of `x`.
	 *
	 * @param x number
	 * @return result
	 */
	template <typename Type>
	Type SignSquare(Type x) {
		if (x < 0.)
			return -x * x;
		return x * x;
	}

	/**
	 * @brief Square root of `abs(x)` with the sign of `x`.
	 *
	 * @param x number
	 * @return result
	 */
	template <typename Type>
	Type SignSquareRoot(Type x) {
		if (x < 0.)
			return -std::sqrt(-x);
		return std::sqrt(x);
	}

	/**
	 * @brief
	 *
	 * @tparam Type
	 * @param x
	 * @return Type
	 */
	template <typename Type>
	Type SinTheta(Type theta) {
		return std::abs(std::sin(theta));
	}

	template <typename Type>
	Type CosTheta(Type theta) {
		if (theta > boost::math::constants::half_pi<Type>())
			return std::cos(theta);
		if (theta < 0.)
			return -std::cos(theta);
		return std::cos(theta);
	}

